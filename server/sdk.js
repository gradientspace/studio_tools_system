// Generates the SDK.luau file that lives at the root of each tool pack's
// source folder. It carries the full SDK type definitions (copied from
// studio_plugin_src/SDK/Types.luau) and, at runtime, simply returns the real
// SDK module, so pack code can use a plain relative require:
//
//     local SDK = require(script.Parent.Parent.SDK)

const fs = require("node:fs");
const path = require("node:path");
const { SRC_DIR } = require("./tree");

const FILE_NAME = "SDK.luau";

function apiVersion() {
  const init = fs.readFileSync(path.join(SRC_DIR, "SDK", "init.luau"), "utf8");
  const match = init.match(/^local API_VERSION = (\d+)/m);
  if (!match) throw new Error("Can't find `local API_VERSION = <n>` in SDK/init.luau");
  return Number(match[1]);
}

function typesBody() {
  const types = fs.readFileSync(path.join(SRC_DIR, "SDK", "Types.luau"), "utf8");
  // Drop the leading block comment and the trailing `return {}`.
  return types
    .replace(/^--\[\[[\s\S]*?\]\]\s*/, "")
    .replace(/\s*return \{\}\s*$/, "")
    .trim();
}

function generate() {
  const version = apiVersion();
  return `--[[
	Studio Tools SDK, API version ${version}.

	GENERATED by \`npm run export-sdk\` in studio_tools_system. Don't edit this
	file; re-run the export to update it.

	Require it with a relative path from any module in this pack, e.g. from
	Tools/MyTool.luau:

		local SDK = require(script.Parent.Parent.SDK)

	The types below describe the SDK and the ToolContext passed to tools. At
	runtime this module just returns the real SDK from the Studio Tools
	framework. See docs/TOOLPACKS.md in studio_tools_system for the contract.
]]

${typesBody()}

return require(script:FindFirstAncestor("StudioTools").SDK) :: SDK
`;
}

// Returns "missing", "outdated" or "current" for a pack's SDK file.
function status(sourceDir, expected = generate()) {
  const file = path.join(sourceDir, FILE_NAME);
  if (!fs.existsSync(file)) return "missing";
  return fs.readFileSync(file, "utf8") === expected ? "current" : "outdated";
}

function write(sourceDir) {
  const file = path.join(sourceDir, FILE_NAME);
  fs.writeFileSync(file, generate());
  return file;
}

module.exports = { FILE_NAME, apiVersion, generate, status, write };
